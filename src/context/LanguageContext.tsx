// Safe locale-aware date and number formatting helpers
export function formatLocalizedDate(date: string | number | Date, langCode: string = "en"): string {
  try {
    const d = new Date(date);
    if (isNaN(d.getTime())) return String(date);
    return new Intl.DateTimeFormat(langCode, {
      dateStyle: "medium",
      timeStyle: "short",
    }).format(d);
  } catch {
    return String(date);
  }
}

export function formatLocalizedNumber(num: number, langCode: string = "en"): string {
  try {
    return new Intl.NumberFormat(langCode).format(num);
  } catch {
    return String(num);
  }
}

interface LanguageContextType {
  language: string;
  setLanguage: (lang: string) => void;
  currentLang: LanguageItem;
  languages: LanguageItem[];
  t: (key: string, fallback?: string) => string;
  formatDate: (date: string | number | Date) => string;
  formatNumber: (num: number) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<string>(() => {
    return safeStorage.getItem("infoatlas_language") || "en";
  });

  const setLanguage = (lang: string) => {
    setLanguageState(lang);
    safeStorage.setItem("infoatlas_language", lang);
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      // Set dir for RTL languages like Arabic
      if (lang === "ar") {
        document.documentElement.dir = "rtl";
      } else {
        document.documentElement.dir = "ltr";
      }
    }
  };

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = language;
      if (language === "ar") {
        document.documentElement.dir = "rtl";
      } else {
        document.documentElement.dir = "ltr";
      }
    }
  }, [language]);

  const currentLang =
    SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    const enDict = TRANSLATIONS.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return fallback || key;
  };

  const formatDate = (date: string | number | Date): string => {
    return formatLocalizedDate(date, language);
  };

  const formatNumber = (num: number): string => {
    return formatLocalizedNumber(num, language);
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        currentLang,
        languages: SUPPORTED_LANGUAGES,
        t,
        formatDate,
        formatNumber,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
